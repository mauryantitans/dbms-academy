#!/usr/bin/env bash
# Starts DB Academy in a dev container / GitHub Codespace: on first run writes .env with random secrets
# (.env is gitignored), then builds and starts the Docker Compose stack. The site is served on port 8080.
set -euo pipefail
cd "$(dirname "$0")/.."

secret() { head -c 40 /dev/urandom | base64 | tr -dc 'A-Za-z0-9'; }

if [ ! -f .env ]; then
  {
    echo "# Generated by .devcontainer/start.sh. Never commit this file."
    for key in SECRET_KEY APP_DB_ROOT_PASSWORD APP_DB_PASSWORD SANDBOX_ROOT_PASSWORD SANDBOX_ADMIN_PASSWORD; do
      echo "$key=$(secret)"
    done
  } > .env
  chmod 600 .env
fi

# The Docker daemon (docker-in-docker feature) starts with the container; wait until it answers.
for _ in $(seq 1 60); do
  docker info >/dev/null 2>&1 && break
  sleep 2
done

docker compose up --build -d
echo "DB Academy is starting on port 8080. Open it from the Ports tab (allow about a minute for MySQL on first start)."
